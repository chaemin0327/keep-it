-- Apply once to a new, dedicated PostgreSQL database using an administrative connection.
-- Do not expose the keepit schema through the Supabase Data API.
CREATE SCHEMA IF NOT EXISTS keepit;
CREATE TABLE keepit.accounts (email varchar(160) PRIMARY KEY, password_hash varchar(100) NOT NULL, session_version bigint, verified boolean);
CREATE TABLE keepit.email_tokens (token_hash varchar(64) PRIMARY KEY, email varchar(160) NOT NULL, expires_at timestamp(6) with time zone NOT NULL, purpose varchar(20) NOT NULL);
CREATE INDEX email_tokens_email_purpose ON keepit.email_tokens (email,purpose);
CREATE TABLE keepit.experience (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    award_name varchar(100), challenge varchar(5000), credential_number varchar(160), custom_category varchar(30),
    demo boolean NOT NULL, description varchar(10000), end_date date, featured boolean NOT NULL,
    link varchar(1000), location varchar(160), ongoing boolean NOT NULL, organization varchar(160),
    outcome varchar(1000), owner varchar(160), participants varchar(300), placement varchar(40), role varchar(200),
    start_date date NOT NULL, tags varchar(300), title varchar(120) NOT NULL, type varchar(32) NOT NULL,
    CONSTRAINT experience_type_check CHECK (type IN ('PROJECT','COMPETITION','AWARD','CERTIFICATE','PAPER','OVERSEAS','ACTIVITY','EDUCATION','WORK','CUSTOM'))
);
CREATE INDEX experience_owner_start_date ON keepit.experience (owner,start_date);
CREATE TABLE keepit.experience_links (experience_id bigint NOT NULL REFERENCES keepit.experience(id), url varchar(1000) NOT NULL, link_order integer NOT NULL, PRIMARY KEY(experience_id,link_order));
CREATE TABLE keepit.profile (id bigint PRIMARY KEY, bio varchar(2000), email varchar(160), headline varchar(160), name varchar(50));
CREATE TABLE keepit.user_profile (owner varchar(160) PRIMARY KEY, bio varchar(2000), email varchar(160), headline varchar(160), name varchar(50));
REVOKE ALL ON SCHEMA keepit FROM PUBLIC;
